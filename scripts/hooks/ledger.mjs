// Pure logic behind `scripts/kiro-ledger.mjs`: turn `git log` text into the
// ledger tables. No I/O and no clock, so the same log always gives the same text.
//
// The log text is produced by `git log --format=%h%x1f%aI%x1f%s` (one commit per line).

export const LOG_FORMAT = '%h%x1f%aI%x1f%s';

// "(spec export, task 5)", "(spec agent-harness, tasks 6 and 7a)", "(spec x, task 5, in progress)".
const TASK_RE = /\(spec\s+([A-Za-z0-9][\w-]*)\s*,\s*tasks?\s+([^)]*)\)/i;
// "docs(specs): add the english-ui spec (...)" and the older "docs(spec): add the export spec".
const SPEC_ADDED_RE = /^docs\(specs?\)!?:\s+add the ([A-Za-z0-9][\w-]*) spec\b/i;

/** Task ids named in the text after "task(s)": "6 and 7a" gives ["6", "7a"]; "1-3" gives ["1", "2", "3"]. */
function taskIds(text) {
  const cleaned = text.replace(/in progress/gi, ' ');
  const ids = [];
  const range = /\b(\d+)\s*(?:-|–|to)\s*(\d+)\b/g;
  for (const m of cleaned.matchAll(range)) {
    const [from, to] = [Number(m[1]), Number(m[2])];
    if (to >= from && to - from < 50) for (let n = from; n <= to; n++) ids.push(String(n));
  }
  const rest = cleaned.replace(range, ' ');
  for (const m of rest.matchAll(/\b\d+[A-Za-z]?\b/g)) ids.push(m[0].toLowerCase());
  return [...new Set(ids)];
}

/**
 * @param {string} logText output of `git log --format=%h%x1f%aI%x1f%s`
 * @returns {{ taskCommits: TaskCommit[], specCommits: SpecCommit[] }}
 *
 * @typedef {{ hash: string, date: string, time: number, spec: string, tasks: string[], inProgress: boolean, subject: string }} TaskCommit
 * @typedef {{ hash: string, date: string, time: number, spec: string, subject: string }} SpecCommit
 */
export function parseLog(logText) {
  const taskCommits = [];
  const specCommits = [];
  for (const line of String(logText).split(/\r?\n/)) {
    const [hash, iso, ...rest] = line.split('\x1f');
    if (!hash || !iso || !rest.length) continue;
    const subject = rest.join('\x1f').trim();
    const time = Date.parse(iso);
    if (Number.isNaN(time)) continue;
    const date = iso.slice(0, 10); // the author's own calendar date, independent of this machine's time zone
    const t = TASK_RE.exec(subject);
    if (t) {
      const tasks = taskIds(t[2]);
      if (tasks.length) {
        taskCommits.push({ hash, date, time, spec: t[1], tasks, inProgress: /in progress/i.test(t[2]), subject });
      }
    }
    const s = SPEC_ADDED_RE.exec(subject);
    if (s) specCommits.push({ hash, date, time, spec: s[1], subject });
  }
  const byTime = (a, b) => a.time - b.time || (a.hash < b.hash ? -1 : a.hash > b.hash ? 1 : 0);
  taskCommits.sort(byTime);
  specCommits.sort(byTime);
  return { taskCommits, specCommits };
}

/** Natural order for ids such as 1, 2, 4, 4b, 5, 10. */
export function compareTaskIds(a, b) {
  const [na, nb] = [parseInt(a, 10), parseInt(b, 10)];
  if (na !== nb) return na - nb;
  return a < b ? -1 : a > b ? 1 : 0;
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/**
 * Per-spec numbers and overall totals.
 * @param {{ taskCommits: TaskCommit[], specCommits: SpecCommit[] }} parsed
 */
export function totals({ taskCommits, specCommits }) {
  const specs = new Map();
  const entry = (name) => {
    if (!specs.has(name)) specs.set(name, { spec: name, commits: 0, tasks: new Set(), added: null });
    return specs.get(name);
  };
  for (const c of taskCommits) {
    const e = entry(c.spec);
    e.commits += 1;
    for (const t of c.tasks) e.tasks.add(t);
  }
  for (const c of specCommits) {
    const e = entry(c.spec);
    if (!e.added) e.added = c; // specCommits is sorted by time, so this is the first one
  }
  const rows = [...specs.values()]
    .map((e) => ({ spec: e.spec, commits: e.commits, tasks: [...e.tasks].sort(compareTaskIds), added: e.added }))
    .sort((a, b) => (a.spec < b.spec ? -1 : a.spec > b.spec ? 1 : 0));
  return {
    rows,
    taskCommits: taskCommits.length,
    distinctTasks: rows.reduce((n, r) => n + r.tasks.length, 0),
    specsWithTasks: rows.filter((r) => r.tasks.length).length,
    specsAdded: rows.filter((r) => r.added).length,
  };
}

/** The text of `.kiro/ledger/README.md`. */
export function renderLedger(parsed) {
  const t = totals(parsed);
  const out = [];
  out.push('# Kiro ledger');
  out.push('');
  out.push('Generated by `node scripts/kiro-ledger.mjs` from `git log`. Do not edit by hand: run the command again after new commits.');
  out.push('');
  out.push('A task commit is a commit whose subject names a spec task as `(spec <name>, task <n>)`. A spec commit is a `docs(spec)` or `docs(specs)` commit that adds a spec. A task can have several commits (fixes, follow-ups), so task commits and distinct tasks are counted separately.');
  out.push('');
  out.push('## Totals');
  out.push('');
  out.push(`- Task commits: ${t.taskCommits}`);
  out.push(`- Distinct spec tasks committed: ${t.distinctTasks}`);
  out.push(`- Specs with task commits: ${t.specsWithTasks}`);
  out.push(`- Specs added by \`docs(spec)\` / \`docs(specs)\` commits: ${t.specsAdded}`);
  out.push('');
  out.push('| Spec | Task commits | Distinct tasks | Tasks | Spec added |');
  out.push('|---|---:|---:|---|---|');
  for (const r of t.rows) {
    out.push(`| ${cell(r.spec)} | ${r.commits} | ${r.tasks.length} | ${r.tasks.length ? r.tasks.join(', ') : '-'} | ${r.added ? `${r.added.date} \`${r.added.hash}\`` : '-'} |`);
  }
  out.push('');
  out.push('A spec added in some other kind of commit (for example together with the steering files) shows `-` under "Spec added".');
  out.push('');
  out.push('## Spec commits');
  out.push('');
  out.push('| Date | Spec | Commit | Subject |');
  out.push('|---|---|---|---|');
  for (const c of parsed.specCommits) out.push(`| ${c.date} | ${cell(c.spec)} | \`${c.hash}\` | ${cell(c.subject)} |`);
  out.push('');
  out.push('## Task commits');
  out.push('');
  out.push('| Date | Spec | Task | Commit | Subject |');
  out.push('|---|---|---|---|---|');
  for (const c of parsed.taskCommits) {
    const task = `${c.tasks.join(', ')}${c.inProgress ? ' (in progress)' : ''}`;
    out.push(`| ${c.date} | ${cell(c.spec)} | ${task} | \`${c.hash}\` | ${cell(c.subject)} |`);
  }
  out.push('');
  return out.join('\n');
}
